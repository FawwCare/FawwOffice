// ─── 설문 통계 자동 계산 함수 ────────────────────────────────────
export function calculateSurveyStats(
  scheduleId: string,
  responses: SurveyResponse[]
): SurveyStats {
  const total = responses.length;

  if (total === 0) {
    return {
      scheduleId,
      totalResponses: 0,
      overallScore: 0,
      positiveRate: 0,
      metrics: [],
      workTypeDistribution: [],
      genderDistribution: [],
      ageDistribution: [],
      locationDistribution: [],
      jointPainDistribution: [],
      musclePainDistribution: [],
      goodFeedbacks: [],
      improveFeedbacks: [],
      futureFeedbacks: [],
    };
  }

  const avg = (fn: (r: SurveyResponse) => number) => {
    const sum = responses.reduce((acc, cur) => acc + fn(cur), 0);
    return Number((sum / total).toFixed(2));
  };

  // 6개 평가 항목
  const metrics: RatingMetric[] = [
    { key: 'ratingOverall', label: '전체 프로그램 만족도', shortLabel: '전체 만족도', average: avg((r) => r.ratingOverall) },
    { key: 'ratingTime', label: '프로그램 시간 적절성', shortLabel: '시간 적절성', average: avg((r) => r.ratingTime) },
    { key: 'ratingInstructor', label: '강사의 전문성 만족도', shortLabel: '강사 전문성', average: avg((r) => r.ratingInstructor) },
    { key: 'ratingRecommend', label: '타인 추천 의향', shortLabel: '추천 의향', average: avg((r) => r.ratingRecommend) },
    { key: 'ratingParticipateAgain', label: '향후 재참여 의향', shortLabel: '재참여 의향', average: avg((r) => r.ratingParticipateAgain) },
    { key: 'ratingImprovement', label: '수강 전후 개선 체감도', shortLabel: '전후 개선 체감', average: avg((r) => r.ratingImprovement) },
  ];

  const overallScore = avg((r) => r.ratingOverall);
  const positiveCount = responses.filter((r) => r.ratingOverall >= 4).length;
  const positiveRate = Math.round((positiveCount / total) * 100);

  // 분포 계산 헬퍼
  const getDistribution = (fn: (r: SurveyResponse) => string) => {
    const counts: Record<string, number> = {};
    responses.forEach((r) => {
      const val = fn(r);
      counts[val] = (counts[val] || 0) + 1;
    });
    return Object.entries(counts).map(([name, value]) => ({ name, value }));
  };

  // 다중선택 배열 분포 계산 헬퍼 (통증 부위)
  const getArrayDistribution = (fn: (r: SurveyResponse) => string[]) => {
    const counts: Record<string, number> = {};
    responses.forEach((r) => {
      const arr = fn(r);
      arr.forEach((item) => {
        counts[item] = (counts[item] || 0) + 1;
      });
    });
    return Object.entries(counts)
      .map(([name, count]) => ({
        name,
        count,
        percentage: Math.round((count / total) * 100),
      }))
      .sort((a, b) => b.count - a.count);
  };

  return {
    scheduleId,
    totalResponses: total,
    overallScore,
    positiveRate,
    metrics,
    workTypeDistribution: getDistribution((r) => r.workType),
    genderDistribution: getDistribution((r) => r.gender),
    ageDistribution: getDistribution((r) => r.ageGroup).sort((a, b) => a.name.localeCompare(b.name)),
    locationDistribution: getDistribution((r) => r.workLocation),
    jointPainDistribution: getArrayDistribution((r) => r.jointPain),
    musclePainDistribution: getArrayDistribution((r) => r.musclePain),
    goodFeedbacks: responses.map((r) => r.feedbackGood).filter(Boolean) as string[],
    improveFeedbacks: responses.map((r) => r.feedbackImprove).filter(Boolean) as string[],
    futureFeedbacks: responses.map((r) => r.feedbackFutureProgram).filter(Boolean) as string[],
  };
}
